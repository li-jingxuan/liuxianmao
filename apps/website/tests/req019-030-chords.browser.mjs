import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const require = createRequire(import.meta.url);
const viteRequire = createRequire(require.resolve("vitest/package.json"));
const { createServer } = await import(pathToFileURL(viteRequire.resolve("vite")).href);
const { chromium } = await import(process.env.LXM_PLAYWRIGHT_MODULE ?? "playwright");
const website = fileURLToPath(new URL("..", import.meta.url));
const artifacts = path.resolve(website, "../../output/playwright/req017-030");
const server = await createServer({
  root: website, configFile: false, cacheDir: path.resolve(website, "node_modules/.vite/req019-030-chords"),
  resolve: { dedupe: ["react", "react-dom"] }, esbuild: { jsx: "automatic" },
  optimizeDeps: { entries: ["tests/req019-030-chords.browser.tsx"], include: ["react", "react-dom", "react-dom/client", "react/jsx-runtime", "next/link"] },
  define: { "process.env.NEXT_PUBLIC_BASE_PATH": '""' },
  server: { host: "127.0.0.1", port: 0, hmr: false, watch: null, fs: { allow: [path.resolve(website, "../..")] } },
  plugins: [{ name: "req019-030-chords", configureServer(dev) {
    dev.middlewares.use(async (request, response, next) => {
      if (request.url !== "/__chords__") return next();
      response.setHeader("Content-Type", "text/html");
      response.end(await dev.transformIndexHtml(request.url, '<!doctype html><div id="root"></div><script type="module" src="/tests/req019-030-chords.browser.tsx"></script>'));
    });
  } }],
});
let browser;
const errors = [];
const checks = [];
try {
  await mkdir(artifacts, { recursive: true });
  await server.listen();
  browser = await chromium.launch({ headless: true, channel: process.env.LXM_BROWSER_CHANNEL ?? "chrome" });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(15000);
  page.on("pageerror", error => errors.push(error.message));
  const button = (root, name) => root.getByRole("button", { name: /^\p{Script=Han}{2}$/u.test(name) ? new RegExp(`^${[...name].join("\\s*")}$`) : name, exact: true });
  const snapshot = () => page.evaluate(() => {
    const state = window.coexistStore.getState();
    return { document: state.document, history: state.historyDepth };
  });
  const sidebar = page.getByRole("complementary", { name: "编辑器属性" });
  const svg = page.getByRole("application", { name: "六线谱编辑器" });
  const popover = page.locator("#chord-edit-popover");
  const library = page.getByRole("dialog", { name: /^和弦库/ });
  const custom = page.getByRole("dialog", { name: /^自定义指法/ });
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/__chords__`, { waitUntil: "commit" });
  await sidebar.waitFor({ timeout: 90000 });
  const chord = await page.evaluate(() => window.coexistStore.getState().document.score.tracks[0].measures.flatMap(m => m.chordSymbols).find(c => c.chord.diagram));
  await svg.getByText(chord.chord.name, { exact: true }).first().click();
  const quickName = page.locator("#chord-popover-name");
  const sideName = sidebar.getByRole("textbox", { name: "和弦名称", exact: true });
  await quickName.waitFor();
  await page.waitForFunction(() => document.querySelectorAll('#chord-edit-popover [aria-label="本调常用和弦"] button').length === 7);
  const baseline = await snapshot();
  assert.equal(await sidebar.getByRole("radio").count(), 2);
  assert.equal(await sidebar.getByLabel("本调常用和弦", { exact: true }).getByRole("button").count(), 8);
  assert.equal(await sidebar.getByRole("button", { name: "更多和弦", exact: true }).count(), 0);
  await button(popover, "应用").waitFor();
  await sidebar.getByLabel("本调常用和弦", { exact: true }).getByRole("button").filter({ has: page.getByText("Am", { exact: true }) }).click();
  assert.equal(await quickName.inputValue(), "Am");
  assert.equal(await sideName.inputValue(), "Am");
  assert.deepEqual(await snapshot(), baseline);
  checks.push("快捷和弦共享草稿且不隐式应用");
  await page.screenshot({ path: path.join(artifacts, "chords-editor-1440.png"), animations: "disabled" });
  await button(popover, "更多和弦").click();
  const popup = page.locator(".ant-dropdown:not(.ant-dropdown-hidden)");
  await popup.getByRole("textbox", { name: "搜索全部和弦", exact: true }).waitFor();
  assert.equal(await popup.getByRole("img", { name: "指法图预览", exact: true }).count(), 8);
  await page.waitForFunction(() => [...document.querySelectorAll('.ant-dropdown:not(.ant-dropdown-hidden)')].every(n => getComputedStyle(n).opacity === "1" && !/(?:appear|enter)(?:-active|-prepare)?(?:\s|$)/.test(n.className)));
  await page.screenshot({ path: path.join(artifacts, "chords-more-1440.png"), animations: "disabled" });
  const cardBoxes = await popup.getByRole("img", { name: "指法图预览", exact: true }).evaluateAll(nodes => nodes.map(n => { const r = n.getBoundingClientRect(); return { x: r.x, y: r.y }; }));
  assert.equal(new Set(cardBoxes.map(box => Math.round(box.y))).size, 2);
  assert.equal(new Set(cardBoxes.map(box => Math.round(box.x))).size, 4);
  checks.push("气泡更多真实图卡为4列2行");
  await button(popup, "浏览完整和弦库").click();
  await library.waitFor();
  assert.deepEqual(await library.getByRole("tab").allTextContents(), ["全部和弦", "我的指法"]);
  const list = library.getByTestId("chord-library-scroll");
  const detail = library.getByTestId("chord-library-detail");
  await library.getByLabel("和弦候选", { exact: true }).getByRole("button").filter({ has: page.getByText("C", { exact: true }) }).click();
  await list.evaluate(node => { node.scrollTop = 0; });
  await page.mouse.move(0, 0);
  await page.screenshot({ path: path.join(artifacts, "chords-library-all-1440.png"), animations: "disabled" });
  await library.getByLabel("和弦候选", { exact: true }).getByRole("button").filter({ has: page.getByText("G7", { exact: true }) }).click();
  const detailBefore = await detail.boundingBox();
  await list.evaluate(node => { node.scrollTop = 900; });
  assert.deepEqual(await detail.boundingBox(), detailBefore);
  assert.ok(await list.evaluate(node => node.scrollTop > 0));
  await page.screenshot({ path: path.join(artifacts, "chords-library-scroll-1440.png"), animations: "disabled" });
  await library.getByLabel("临时浏览大小调", { exact: true }).click();
  await page.locator(".ant-select-dropdown:visible").getByText("小调", { exact: true }).click();
  await library.getByText("和声小调补充", { exact: true }).waitFor();
  await page.locator(".ant-select-dropdown:visible").waitFor({ state: "hidden" });
  assert.deepEqual(await snapshot(), baseline);
  await page.screenshot({ path: path.join(artifacts, "chords-library-1440.png"), animations: "disabled" });
  checks.push("库仅两页签、自然/和声小调分类、浏览不改曲谱、左滚动右固定");
  await library.getByRole("tab", { name: "我的指法", exact: true }).click();
  await library.getByText("还没有保存的指法。可在“自定义指法”中另存。", { exact: true }).waitFor();
  await page.screenshot({ path: path.join(artifacts, "chords-library-mine-1440.png"), animations: "disabled" });
  await library.getByRole("tab", { name: "全部和弦", exact: true }).click();
  await button(library, "选用此指法").click();
  await library.waitFor({ state: "hidden" });
  assert.equal(await quickName.inputValue(), "G7");
  assert.deepEqual(await snapshot(), baseline);
  await button(popover, "应用").click();
  assert.notDeepEqual(await snapshot(), baseline);
  checks.push("库选用只回填，名称旁应用才写谱面");
  const applied = await snapshot();
  await button(popover, "编辑指法").click();
  await custom.waitFor();
  await custom.getByRole("textbox", { name: "自定义和弦名称", exact: true }).fill("我的G7");
  await button(custom, "另存为我的指法").click();
  await custom.getByText(/已保存到我的指法/).waitFor();
  await button(custom, "取消").click();
  await custom.waitFor({ state: "hidden" });
  assert.equal(await quickName.inputValue(), "G7");
  assert.deepEqual(await snapshot(), applied);
  await button(sidebar, "更多配置").click();
  await library.waitFor();
  await library.getByRole("tab", { name: "我的指法", exact: true }).click();
  await library.getByRole("button").filter({ has: page.getByText("我的G7", { exact: true }) }).click();
  await page.screenshot({ path: path.join(artifacts, "chords-library-mine-saved-1440.png"), animations: "disabled" });
  await button(library, "选用此指法").click();
  await library.waitFor({ state: "hidden" });
  assert.equal(await quickName.inputValue(), "我的G7");
  assert.deepEqual(await snapshot(), applied);
  checks.push("我的指法读取真实浏览器收藏且选用只回填");
  await button(popover, "编辑指法").click();
  await custom.waitFor();
  await custom.getByRole("textbox", { name: "自定义和弦名称", exact: true }).fill("完成G7");
  await button(custom, "完成编辑").click();
  await custom.waitFor({ state: "hidden" });
  assert.equal(await quickName.inputValue(), "完成G7");
  assert.equal(await sideName.inputValue(), "完成G7");
  assert.deepEqual(await snapshot(), applied);
  checks.push("自定义完成只回填共享草稿且不写谱面");
  await sidebar.getByRole("radio", { name: "仅名称", exact: true }).check();
  assert.deepEqual(await snapshot(), applied);
  await button(sidebar, "应用").click();
  checks.push("自定义取消保持草稿，显示单选等待统一应用");
  const beforeDelete = await snapshot();
  await button(sidebar, "删除").click();
  assert.equal(await sideName.inputValue(), "");
  assert.equal(await quickName.inputValue(), "");
  const removed = await page.evaluate(() => {
    const state = window.coexistStore.getState(), target = state.selection.focus;
    return state.document.score.tracks.find(t => t.id === target.trackId).measures.find(m => m.id === target.measureId).chordSymbols.some(c => c.beatId === target.beatId);
  });
  assert.equal(removed, false);
  await page.screenshot({ path: path.join(artifacts, "chords-deleted-1440.png"), animations: "disabled" });
  checks.push("名称标签删除立即生效并清空共享输入");
  await button(page.getByRole("toolbar", { name: "节奏、小节与历史工具" }), "撤销").click();
  assert.deepEqual((await snapshot()).document, beforeDelete.document);
  checks.push("立即删除支持正式历史撤销");
  await page.setViewportSize({ width: 1400, height: 720 });
  await button(sidebar, "更多配置").click();
  await library.waitFor();
  await library.getByLabel("和弦候选", { exact: true }).getByRole("button").filter({ has: page.getByText("C", { exact: true }) }).click();
  await page.screenshot({ path: path.join(artifacts, "chords-library-1400x720.png"), animations: "disabled" });
  const confirmBox = await button(library, "选用此指法").boundingBox();
  assert.ok(confirmBox && confirmBox.y >= 0 && confirmBox.y + confirmBox.height <= 720);
  await button(library, "选用此指法").click({ trial: true });
  await button(library, "取消").click();
  checks.push("1400×720库详情及确认操作可达");
  assert.deepEqual(errors, []);
  await writeFile(path.join(artifacts, "chords-result.json"), JSON.stringify({ checks, errors }, null, 2));
  console.log(JSON.stringify({ checks, errors, artifacts }, null, 2));
} finally {
  if (browser) await browser.close();
  await server.close();
}
